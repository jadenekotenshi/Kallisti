#!/usr/bin/env python3
"""Regenerates core/roots_bundled.c: the root certificates compiled into Kallisti as the fallback trust store.

usage: tools/gen_roots.py /path/to/ca-bundle.pem > core/roots_bundled.c
The bundle is any PEM file of root certificates (macOS: /etc/ssl/cert.pem, Mozilla's cacert.pem).  The roots
kept are the ones whose subject contains one of WANTED: the authorities behind Cloudflare, Google, Amazon and
Let's Encrypt, which is where Discord's certificates come from.  Expired roots are left out.
"""
import base64, datetime, hashlib, re, subprocess, sys

WANTED = [
    'GTS Root R1', 'GTS Root R2', 'GTS Root R3', 'GTS Root R4',
    'GlobalSign Root CA', 'GlobalSign Root CA - R3', 'GlobalSign Root CA - R6',
    'GlobalSign ECC Root CA - R4', 'GlobalSign ECC Root CA - R5',
    'ISRG Root X1', 'ISRG Root X2',
    'DigiCert Global Root CA', 'DigiCert Global Root G2', 'DigiCert Global Root G3', 'DigiCert Trusted Root G4',
    'USERTrust RSA Certification Authority', 'USERTrust ECC Certification Authority',
    'COMODO RSA Certification Authority', 'COMODO ECC Certification Authority',
    'SSL.com Root Certification Authority RSA', 'SSL.com Root Certification Authority ECC',
    'SSL.com EV Root Certification Authority RSA R2', 'SSL.com EV Root Certification Authority ECC',
    'Amazon Root CA 1', 'Amazon Root CA 2', 'Amazon Root CA 3', 'Amazon Root CA 4',
    'Starfield Root Certificate Authority - G2', 'Starfield Services Root Certificate Authority - G2',
]

def openssl(args, data):
    return subprocess.run(['openssl'] + args, input=data, capture_output=True, text=True, check=True).stdout

bundle = open(sys.argv[1]).read()
blocks = re.findall(r'-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----', bundle, re.S)
now = datetime.datetime.utcnow()
chosen = []
for b in blocks:
    subj = openssl(['x509', '-noout', '-subject', '-nameopt', 'RFC2253'], b).strip().split('=', 1)[1]
    values = [t.split('=', 1)[1] for t in subj.split(',') if '=' in t]
    end = openssl(['x509', '-noout', '-enddate'], b).strip().split('=', 1)[1]
    exp = datetime.datetime.strptime(' '.join(end.split()[:4]), '%b %d %H:%M:%S %Y')
    for w in WANTED:
        if w in values:                      # an exact CN or OU value
            if exp >= now:
                chosen.append((w, exp, b))
            break

seen = set()
out = []
out.append('/* GENERATED by tools/gen_roots.py -- do not edit.  The root certificates compiled in as the fallback trust')
out.append(' * store (used when /usr/local/ssl has none).  See tools/gen_roots.py for how they were chosen.  Generated %s. */' % now.strftime('%Y-%m-%d'))
out.append('#include "roots.h"')
out.append('')
entries = []
for i, (name, exp, b) in enumerate(chosen):
    der = base64.b64decode(''.join(b.split('\n')[1:-1]))
    fp = hashlib.sha256(der).hexdigest()
    if fp in seen:
        continue
    seen.add(fp)
    idx = len(entries)
    out.append('/* %s -- expires %s -- SHA256 %s */' % (name, exp.strftime('%Y-%m-%d'), fp))
    out.append('static const unsigned char root_%d[%d] = {' % (idx, len(der)))
    for j in range(0, len(der), 12):
        out.append('    ' + ', '.join('0x%02x' % c for c in der[j:j + 12]) + ',')
    out.append('};')
    out.append('')
    entries.append(len(der))
out.append('static const struct { const unsigned char *der; unsigned long len; } roots[] = {')
for idx, n in enumerate(entries):
    out.append('    { root_%d, %d },' % (idx, n))
out.append('    { 0, 0 }')
out.append('};')
out.append('')
out.append('int roots_bundled_load(TrustStore *ts)')
out.append('{')
out.append('    int i, added = 0;')
out.append('')
out.append('    for (i = 0; roots[i].der != 0; i++) {')
out.append('        if (trust_add_der(ts, roots[i].der, (size_t)roots[i].len) == 1) {')
out.append('            added++;')
out.append('        }')
out.append('    }')
out.append('    return added;')
out.append('}')
print('\n'.join(out))
sys.stderr.write('%d roots\n' % len(entries))
